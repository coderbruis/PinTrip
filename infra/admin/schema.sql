CREATE TABLE IF NOT EXISTS pintrip_knowledge_document (
    id VARCHAR(32) PRIMARY KEY,
    title VARCHAR(80) NOT NULL,
    destination VARCHAR(40) NOT NULL,
    source VARCHAR(40) NOT NULL,
    source_type VARCHAR(20) NOT NULL,
    chunk_count INTEGER NOT NULL CHECK (chunk_count > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'indexing',
    error_message VARCHAR(1000),
    tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_knowledge_source_type CHECK (source_type IN ('operator', 'user')),
    CONSTRAINT ck_knowledge_status CHECK (status IN ('indexing', 'published', 'failed', 'offline'))
);

CREATE INDEX IF NOT EXISTS idx_knowledge_document_destination
    ON pintrip_knowledge_document (destination);
CREATE INDEX IF NOT EXISTS idx_knowledge_document_status
    ON pintrip_knowledge_document (status);

CREATE TABLE IF NOT EXISTS pintrip_knowledge_chunk (
    id UUID PRIMARY KEY,
    knowledge_id VARCHAR(32) NOT NULL,
    chunk_index INTEGER NOT NULL CHECK (chunk_index >= 0),
    content TEXT NOT NULL,
    embedding vector(512),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_knowledge_chunk_position UNIQUE (knowledge_id, chunk_index),
    CONSTRAINT fk_knowledge_chunk_document
        FOREIGN KEY (knowledge_id) REFERENCES pintrip_knowledge_document (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_knowledge_chunk_document
    ON pintrip_knowledge_chunk (knowledge_id);
CREATE INDEX IF NOT EXISTS idx_knowledge_chunk_embedding
    ON pintrip_knowledge_chunk
    USING hnsw (embedding vector_cosine_ops);

COMMENT ON TABLE pintrip_knowledge_document IS '运营导入和用户沉淀的攻略知识';
COMMENT ON TABLE pintrip_knowledge_chunk IS '攻略知识切块及其语义向量';
