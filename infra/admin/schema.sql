CREATE TABLE IF NOT EXISTS pintrip_admin_menu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_key VARCHAR(64) NOT NULL,
    parent_key VARCHAR(64),
    menu_name VARCHAR(64) NOT NULL,
    menu_hint VARCHAR(128) NOT NULL,
    route VARCHAR(128),
    icon VARCHAR(32) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    status SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_admin_menu_key UNIQUE (menu_key),
    CONSTRAINT ck_admin_menu_status CHECK (status IN (1, 2))
);

CREATE TABLE IF NOT EXISTS pintrip_admin_role_menu (
    role_id BIGINT NOT NULL,
    menu_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (role_id, menu_id),
    CONSTRAINT fk_admin_role_menu_role FOREIGN KEY (role_id)
        REFERENCES pintrip_admin_role (id) ON DELETE CASCADE,
    CONSTRAINT fk_admin_role_menu_menu FOREIGN KEY (menu_id)
        REFERENCES pintrip_admin_menu (id) ON DELETE CASCADE
);

